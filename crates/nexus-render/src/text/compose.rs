pub(super) fn compose(base: char, mark: char) -> Option<char> {
    TABLE
        .binary_search_by(|&(b, m, _)| (b, m).cmp(&(base, mark)))
        .ok()
        .map(|idx| TABLE[idx].2)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn composes_latin_letters() {
        assert!(TABLE
            .windows(2)
            .all(|pair| (pair[0].0, pair[0].1) < (pair[1].0, pair[1].1)));
        assert_eq!(compose('u', '\u{308}'), Some('ü'));
        assert_eq!(compose('e', '\u{301}'), Some('é'));
        assert_eq!(compose('S', '\u{326}'), Some('\u{218}'));
        assert_eq!(compose('q', '\u{308}'), None);
    }
}
