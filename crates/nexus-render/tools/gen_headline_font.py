#!/usr/bin/env python3
"""Generate src/font_headline.rs from a Terminus PSF2 console font.

Usage:
    python3 -I tools/gen_headline_font.py /usr/share/kbd/consolefonts/ter-120b.psf.gz > src/font_headline.rs

Terminus Font is licensed under the SIL Open Font License 1.1; the license
text ships next to the generated table as src/font_headline.OFL.txt.
"""

import gzip
import struct
import sys

PSF2_MAGIC = 0x864AB572

# Printable ASCII, Latin-1 Supplement + Latin Extended-A, typographic
# punctuation that news feeds use (dashes, curly quotes, ellipsis), euro sign.
RANGES = [
    (0x21, 0x7E),
    (0xA1, 0x17F),
    (0x2010, 0x2027),
    (0x2030, 0x203A),
    (0x20AC, 0x20AC),
    (0x2122, 0x2122),
]


def load_psf2(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    magic, _version, header, flags, count, charsize, height, width = struct.unpack(
        "<8I", data[:32]
    )
    if magic != PSF2_MAGIC:
        sys.exit(f"{path}: not a PSF2 font")
    if not flags & 1:
        sys.exit(f"{path}: font has no unicode table")
    row_bytes = (width + 7) // 8
    glyphs = []
    for idx in range(count):
        off = header + idx * charsize
        rows = []
        for r in range(height):
            raw = int.from_bytes(data[off + r * row_bytes : off + (r + 1) * row_bytes], "big")
            rows.append(raw >> (row_bytes * 8 - width))
        glyphs.append(rows)
    mapping = {}
    table = data[header + count * charsize :]
    pos = 0
    for idx in range(count):
        end = table.index(b"\xff", pos)
        single = table[pos:end].split(b"\xfe")[0].decode("utf-8")
        for ch in single:
            mapping.setdefault(ch, idx)
        pos = end + 1
    return width, height, glyphs, mapping


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    width, height, glyphs, mapping = load_psf2(sys.argv[1])
    wanted = [chr(c) for lo, hi in RANGES for c in range(lo, hi + 1)]
    entries = []
    for ch in wanted:
        idx = mapping.get(ch)
        if idx is None:
            continue
        rows = glyphs[idx]
        mask = 0
        for row in rows:
            mask |= row
        if mask == 0:
            continue
        cols = [c for c in range(width) if mask & (1 << (width - 1 - c))]
        entries.append((ord(ch), cols[0], cols[-1] - cols[0] + 1, rows))

    out = sys.stdout
    out.write("//! Generated by tools/gen_headline_font.py from Terminus Font\n")
    out.write("//! (ter-120b, bold 10x20). Do not edit by hand.\n")
    out.write("//!\n")
    out.write("//! Terminus Font is licensed under the SIL Open Font License 1.1, see\n")
    out.write("//! font_headline.OFL.txt next to this file.\n\n")
    out.write(f"pub(crate) const GLYPH_CELL_WIDTH: usize = {width};\n")
    out.write(f"pub(crate) const GLYPH_HEIGHT: usize = {height};\n\n")
    out.write("/// `(codepoint, first inked column, inked width, rows)`. Row bits are\n")
    out.write(f"/// MSB-first: bit {width - 1} is the leftmost column of the cell.\n")
    out.write("#[rustfmt::skip]\n")
    out.write(f"pub(crate) static GLYPHS: [(u32, u8, u8, [u16; {height}]); {len(entries)}] = [\n")
    for code, left, inked, rows in entries:
        body = ", ".join(f"0x{row:03x}" for row in rows)
        out.write(f"    (0x{code:04x}, {left}, {inked}, [{body}]),\n")
    out.write("];\n")


if __name__ == "__main__":
    main()
